#!/usr/bin/env python3
"""Generate firmware/src/bandplan.h from bandplan.json.

The firmware needs only three facts per branch, so they are packed into
compile-time constants instead of a table:
  BP_LNA_MASK   bit n set -> branch n may use the LNA
  BP_FMN_MASK   bit n set -> FM notch inserted when branch n runs with LNA
  BP_PORT_INIT  PE42582 V3V2V1 control code per branch. 'port' in the json
                is the RF port index (0 = RF1 ... 7 = RF8) the branch is wired
                to; the PE42582 truth table (LS = 0) is not binary, so the
                port is mapped to its code here: RF1 000, RF2 100, RF3 010,
                RF4 110, RF5 001, RF6 101, RF7 011, RF8 111.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "bandplan.json"
DST = ROOT / "firmware" / "src" / "bandplan.h"

# PE42582 datasheet truth table, LS = 0, V4 = 0: RF port index -> V3V2V1
PE42582_CODE = [0b000, 0b100, 0b010, 0b110, 0b001, 0b101, 0b011, 0b111]


def main() -> int:
    plan = json.loads(SRC.read_text(encoding="utf-8"))["branches"]
    if [b["id"] for b in plan] != list(range(8)):
        sys.exit("bandplan.json: need exactly 8 branches with ids 0..7 in order")
    ports = [b["port"] for b in plan]
    if sorted(ports) != list(range(8)):
        sys.exit("bandplan.json: 'port' values must be a permutation of 0..7")

    lna = sum(1 << b["id"] for b in plan if b["lna_ok"])
    fmn = sum(1 << b["id"] for b in plan if b["fm_notch"])
    bad = [b["name"] for b in plan if b["fm_notch"] and not b["lna_ok"]]
    if bad:
        sys.exit(f"bandplan.json: fm_notch needs lna_ok (notch sits in LNA path): {bad}")

    lines = [
        "/* GENERATED by tools/gen_bandplan.py from bandplan.json - do not edit. */",
        "#ifndef COAX_BANDPLAN_H",
        "#define COAX_BANDPLAN_H",
        "",
    ]
    for b in plan:
        lines.append(
            f"/* F{b['id']} {b['name']:<8} RF{b['port'] + 1} code {PE42582_CODE[b['port']]:03b}  {b['filter']:<24}"
            f" LNA:{'yes' if b['lna_ok'] else 'no '} FMN:{'yes' if b['fm_notch'] else 'no '} */"
        )
    lines += [
        "",
        f"#define BP_LNA_MASK 0x{lna:02X}u",
        f"#define BP_FMN_MASK 0x{fmn:02X}u",
        "",
        "/* bank index -> PE42582 V3..V1 code */",
        "#define BP_PORT_INIT { " + ", ".join(str(PE42582_CODE[p]) for p in ports) + " }",
        "",
        "#endif",
        "",
    ]
    DST.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {DST.relative_to(ROOT)}  LNA=0x{lna:02X} FMN=0x{fmn:02X}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
